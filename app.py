@app.route('/')
def index():
    return render_template('index.html')


@app.route('/generate', methods=['POST'])
def generate():
    data = request.json

    api_key = os.environ.get('ANTHROPIC_API_KEY')
    if not api_key:
        return jsonify({'error': 'API 키가 설정되지 않았어요.'}), 500

    client = anthropic.Anthropic(api_key=api_key)

    user_message = f"""다음 아이의 상담 준비 멘트를 C.A.R.E 모델에 맞게 작성해주세요.

**기본 정보**
- 아이 이름: {data.get('child_name', '')}
- 나이: {data.get('child_age', '')}살
- 학부모 성함: {data.get('parent_name', '')}
- 학부모 유형: {data.get('parent_type', '')}

**수업 에피소드** (최근 3~4주 수업에서 기억에 남는 장면)
{data.get('episode', '')}

**글쓰기 변화** (전/후 비교)
{data.get('writing_change', '')}

**태도·습관 변화**
{data.get('attitude_change', '')}

**현재 커리큘럼 위치**
{data.get('curriculum', '')}

**이전 상담 팔로업 / 학부모 목표**
{data.get('followup', '')}"""

    try:
        message = client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=4096,
            system=SYSTEM_PROMPT,
            messages=[{"role": "user", "content": user_message}]
        )
        return jsonify({'result': message.content[0].text})
    except Exception as e:
        return jsonify({'error': str(e)}), 500


if __name__ == '__main__':
    port = int(os.environ.get('PORT', 5000))
    app.run(host='0.0.0.0', port=port, debug=False)
